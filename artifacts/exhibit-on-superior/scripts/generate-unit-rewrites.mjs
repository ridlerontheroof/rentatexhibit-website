#!/usr/bin/env node
// Regenerates the per-unit [[services.production.rewrites]] block in
// .replit-artifact/artifact.toml from the baked availability snapshot
// (src/data/availabilitySnapshot.json), so a publish can add or drop a unit
// without hand-editing the routing file. The prerender parity guard in
// scripts/prerender.mjs remains the safety net: it still fails the build if
// the toml drifts from the snapshot.
//
// Modes:
//   node scripts/generate-unit-rewrites.mjs           # writes artifact.toml in place (atomic)
//   node scripts/generate-unit-rewrites.mjs --check   # exit 1 if the block is out of date, write nothing
//   node scripts/generate-unit-rewrites.mjs --stage   # write .replit-artifact/artifact.edit.toml only
//
// The block boundaries are the existing comment header ("# Per-unit listing
// pages") and the "/knowledge/*" not-found rule that must stay after it; the
// script refuses to run if either anchor is missing or out of order, so it can
// never scribble over unrelated rewrites.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const snapshotPath = path.join(root, 'src', 'data', 'availabilitySnapshot.json');
const tomlPath = path.join(root, '.replit-artifact', 'artifact.toml');

const mode = process.argv.includes('--check')
  ? 'check'
  : process.argv.includes('--stage')
    ? 'stage'
    : 'write';

// --- Read units from the snapshot -------------------------------------------
const snapshot = JSON.parse(fs.readFileSync(snapshotPath, 'utf8'));
if (!Array.isArray(snapshot.units)) {
  throw new Error(`Snapshot ${snapshotPath} has no "units" array.`);
}
// Unit segments are "FFUU" (e.g. 0208) or AppFolio's mezzanine form "04M02".
const UNIT_RE = /^\d{2}M?\d{2}$/;
const units = [...new Set(snapshot.units.map((u) => String(u.unit)))].sort();
for (const u of units) {
  if (!UNIT_RE.test(u)) {
    throw new Error(
      `Refusing to generate rewrites: snapshot unit "${u}" does not match the expected FFUU / FFM UU form.`,
    );
  }
}
if (units.length === 0) {
  console.warn('Snapshot lists zero units; generating an empty per-unit block.');
}

// --- Locate the per-unit block in artifact.toml ------------------------------
const toml = fs.readFileSync(tomlPath, 'utf8');

const HEADER_START = '# Per-unit listing pages (/available-units/<unit>):';
const END_ANCHOR = 'from = "/knowledge/*"';

const startIdx = toml.indexOf(HEADER_START);
if (startIdx === -1) {
  throw new Error(`Anchor comment not found in ${tomlPath}: ${HEADER_START}`);
}
// The end anchor is the comment block introducing the /knowledge/* rule; keep
// everything from that comment onward untouched.
const knowledgeRuleIdx = toml.indexOf(END_ANCHOR, startIdx);
if (knowledgeRuleIdx === -1) {
  throw new Error(`/knowledge/* rule not found after the per-unit block in ${tomlPath}.`);
}
// Walk back from the /knowledge/* rule to the start of its comment/table so
// the regenerated block ends exactly where the next section begins.
const tail = toml.slice(startIdx, knowledgeRuleIdx);
const nextSectionOffset = tail.indexOf('\n# Unknown /knowledge/<slug>');
const endIdx =
  nextSectionOffset !== -1
    ? startIdx + nextSectionOffset + 1
    : startIdx + tail.lastIndexOf('\n[[services.production.rewrites]]') + 1;
if (endIdx <= startIdx) {
  throw new Error('Could not determine the end of the per-unit rewrite block.');
}

// Safety: the region we are replacing must contain ONLY the header comment and
// /available-units/<unit> rewrite pairs — nothing else.
const region = toml.slice(startIdx, endIdx);
const strayRule = [...region.matchAll(/^from = "([^"]+)"$/gm)]
  .map((m) => m[1])
  .find((f) => !/^\/available-units\/\d{2}M?\d{2}\/?$/.test(f));
if (strayRule) {
  throw new Error(
    `Refusing to regenerate: unexpected rewrite "${strayRule}" inside the per-unit block region.`,
  );
}

// --- Build the replacement block ---------------------------------------------
const header = `# Per-unit listing pages (/available-units/<unit>): one prerendered directory
# per unit in the baked availability snapshot. The production static host does
# NOT resolve directory indexes for unmatched paths (verified live 2026-07-26:
# /available-units/<unit>/ fell through to the /* catch-all and served the
# homepage shell), so each unit needs an explicit rewrite pair. These entries
# are pinned to the snapshot by a prerender parity guard (scripts/prerender.mjs);
# a unit NOT listed here intentionally falls through to the SPA catch-all so
# rented units show the graceful client-side "has been rented" page.
# GENERATED by scripts/generate-unit-rewrites.mjs from src/data/availabilitySnapshot.json
# — do not hand-edit this block; rerun the script instead.
`;

const pairs = units
  .map((u) =>
    [
      '[[services.production.rewrites]]',
      `from = "/available-units/${u}"`,
      `to = "/available-units/${u}/index.html"`,
      '',
      '[[services.production.rewrites]]',
      `from = "/available-units/${u}/"`,
      `to = "/available-units/${u}/index.html"`,
      '',
      '',
    ].join('\n'),
  )
  .join('');

const nextToml = toml.slice(0, startIdx) + header + pairs + toml.slice(endIdx);

// --- Post-generation parity self-check (mirrors the prerender guard) ---------
for (const u of units) {
  for (const form of [`/available-units/${u}`, `/available-units/${u}/`]) {
    const rule = `from = "${form}"\nto = "/available-units/${u}/index.html"`;
    if (!nextToml.includes(rule)) {
      throw new Error(`Self-check failed: generated toml is missing the rule for ${form}.`);
    }
  }
}
const generatedUnits = new Set(
  [...nextToml.matchAll(/^from = "\/available-units\/([0-9M]+)\/?"$/gm)].map((m) => m[1]),
);
const stale = [...generatedUnits].filter((u) => !units.includes(u));
if (stale.length) {
  throw new Error(`Self-check failed: stale unit rewrites survived regeneration: ${stale.join(', ')}`);
}

// --- Emit ---------------------------------------------------------------------
if (nextToml === toml) {
  console.log(`Per-unit rewrites already match the snapshot (${units.length} unit(s)); nothing to do.`);
  process.exit(0);
}

if (mode === 'check') {
  console.error(
    `Per-unit rewrites in artifact.toml are OUT OF DATE for snapshot units: ${units.join(', ')}.\n` +
      'Run: node scripts/generate-unit-rewrites.mjs',
  );
  process.exit(1);
}

if (mode === 'stage') {
  const stagePath = path.join(root, '.replit-artifact', 'artifact.edit.toml');
  fs.writeFileSync(stagePath, nextToml);
  console.log(
    `Wrote regenerated toml to ${stagePath} (${units.length} unit(s)).\n` +
      'Apply it via the validated artifact-toml replacement flow.',
  );
  process.exit(0);
}

// write mode: atomic temp-file + rename so a crash can't truncate artifact.toml.
const tmpPath = `${tomlPath}.tmp-${process.pid}`;
fs.writeFileSync(tmpPath, nextToml);
fs.renameSync(tmpPath, tomlPath);
console.log(`Regenerated per-unit rewrites in artifact.toml (${units.length} unit(s)): ${units.join(', ')}`);
